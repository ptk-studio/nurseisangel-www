#!/usr/bin/env python3
"""Build one audience landing page (ptk-studio#191).

    python3 build.py <slug>            -> dist/<slug>/
    python3 build.py <slug> --preview  -> also allows placeholder links (never for production)

A site is sites/<slug>/site.toml (config + products) and sites/<slug>/content.md
(the audience's story). Output: index.html, privacy/index.html, 404.html,
_redirects (/go/<id> -> the product's store link, ONLY for ids in site.toml) and
_headers. Standard library only (Python 3.11+), so Cloudflare Pages builds it as is.
"""
import html, os, re, shutil, sys, tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent
API = "https://api.88eggs.com"
PRODUCT_ID = re.compile(r"[a-z0-9-]{1,64}")
# Product links may only go to these hosts (no open redirect, no surprise destinations).
ALLOWED_HOSTS = {"www.amazon.com", "amazon.com", "shop.88eggs.com", "www.etsy.com"}


class SiteError(Exception):
    pass


def load_site(slug: str) -> dict:
    d = ROOT / "sites" / slug
    site = tomllib.loads((d / "site.toml").read_text(encoding="utf-8"))
    site["slug"] = slug
    site["content_md"] = (d / "content.md").read_text(encoding="utf-8")
    return site


def check_link(url: str, preview: bool) -> bool:
    """True if the link is a real https store link on an allowed host; False for a preview placeholder."""
    if preview and url.startswith("#"):
        return False
    m = re.fullmatch(r"https://([^/?#\s]+)(/\S*)?", url)
    if not m or m.group(1).lower() not in ALLOWED_HOSTS:
        raise SiteError(f"product link not allowed: {url!r} (https on {sorted(ALLOWED_HOSTS)} only)")
    return True


def validate(site: dict, preview: bool) -> None:
    for key in ("domain", "title", "audience", "market", "accent"):
        if not site.get(key):
            raise SiteError(f"site.toml: {key} is required")
    seen = set()
    for p in site.get("products", []):
        if not PRODUCT_ID.fullmatch(p.get("id", "")):
            raise SiteError(f"bad product id {p.get('id')!r} (a-z, 0-9, -)")
        if p["id"] in seen:
            raise SiteError(f"duplicate product id {p['id']}")
        seen.add(p["id"])
        if p.get("status", "coming") not in ("coming", "live"):
            raise SiteError(f"{p['id']}: status must be coming or live")
        # A "coming" product needs no link (no button, no redirect). A live one needs a real store link.
        if p.get("status") == "live" or p.get("link"):
            if not p.get("link"):
                raise SiteError(f"{p['id']}: a live product needs a link")
            check_link(p["link"], preview)


def tagged(url: str, slug: str) -> str:
    sep = "&" if "?" in url else "?"
    return f"{url}{sep}src={slug}"


def md_to_html(md: str) -> str:
    out, para = [], []
    def inline(t: str) -> str:
        t = html.escape(t)
        t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
        t = re.sub(r"\[([^\]]+)\]\((https://[^)\s]+|/[^)\s]*)\)", r'<a href="\2">\1</a>', t)
        return t
    def flush():
        if para:
            out.append(f"<p>{inline(' '.join(para))}</p>")
            para.clear()
    for line in md.splitlines():
        s = line.strip()
        h = re.match(r"^(#{1,3})\s+(.*)$", s)
        if h:
            flush(); n = len(h.group(1))
            out.append(f"<h{n}>{inline(h.group(2))}</h{n}>")
        elif not s:
            flush()
        else:
            para.append(s)
    flush()
    return "\n".join(out)


def render(template: str, **values: str) -> str:
    text = (ROOT / "templates" / template).read_text(encoding="utf-8")
    for k, v in values.items():
        text = text.replace("{{" + k + "}}", v)
    left = re.findall(r"\{\{\w+\}\}", text)
    if left:
        raise SiteError(f"{template}: unfilled {left}")
    return text


def product_cards(site: dict, preview: bool) -> str:
    cards = []
    for p in site.get("products", []):
        live = is_live(p, preview)
        img = (f'<img src="/img/{html.escape(p["image"])}" alt="{html.escape(p["name"])}" loading="lazy">'
               if p.get("image") else '<div class="ph" aria-hidden="true"></div>')
        action = (f'<a class="buy" href="/go/{p["id"]}" data-product="{p["id"]}" rel="nofollow">'
                  f'{html.escape(p.get("cta", "See it on " + p["store"]))}</a>'
                  if live else '<span class="soon">Coming soon</span>')
        cards.append(f'<li class="card">{img}<h3>{html.escape(p["name"])}</h3>'
                     f'<p class="meta">{html.escape(p["type"])} · {html.escape(p["price"])} · {html.escape(p["store"])}</p>'
                     f'<p>{html.escape(p.get("blurb", ""))}</p>{action}</li>')
    return "\n".join(cards)


def is_live(p: dict, preview: bool) -> bool:
    return p.get("status") == "live" and bool(p.get("link")) and check_link(p["link"], preview)


def redirects(site: dict, preview: bool) -> str:
    lines = ["# Generated by build.py from site.toml: ONLY these ids redirect (no open redirect)."]
    for p in site.get("products", []):
        if is_live(p, preview):
            lines.append(f"/go/{p['id']} {tagged(p['link'], site['slug'])} 302")
    return "\n".join(lines) + "\n"


BEACON = (ROOT / "templates" / "beacon.html").read_text(encoding="utf-8")

HEADERS = """/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()
  Content-Security-Policy: default-src 'self'; img-src 'self' data: https:; style-src 'self' 'unsafe-inline'; script-src 'self' 'unsafe-inline' https://api.88eggs.com; connect-src https://api.88eggs.com; frame-ancestors 'none'; base-uri 'self'; form-action 'self'
"""


def build(slug: str, preview: bool = False) -> Path:
    site = load_site(slug)
    validate(site, preview)
    out = ROOT / "dist" / slug
    if out.exists():
        shutil.rmtree(out)
    (out / "privacy").mkdir(parents=True)
    feedback = (f'<script src="{API}/feedback/widget.js?v=2" data-key="{html.escape(site["feedback_key"])}" '
                f'data-label="Feedback" async></script>' if site.get("feedback_key") else "")
    common = dict(beacon=BEACON.replace("{{api}}", API).replace("{{slug}}", slug),
        title=html.escape(site["title"]), domain=html.escape(site["domain"]), accent=html.escape(site["accent"]),
        slug=slug, api=API, feedback=feedback, disclosure=html.escape(site.get("disclosure", "")),
        brand=html.escape(site.get("brand", "")), year="2026",
    )
    (out / "index.html").write_text(render("index.html", **common,
        description=html.escape(site.get("description", "")), story=md_to_html(site["content_md"]),
        products=product_cards(site, preview)), encoding="utf-8")
    (out / "privacy" / "index.html").write_text(render("privacy.html", **common), encoding="utf-8")
    (out / "404.html").write_text(render("404.html", **common), encoding="utf-8")
    (out / "_redirects").write_text(redirects(site, preview), encoding="utf-8")
    (out / "_headers").write_text(HEADERS, encoding="utf-8")
    img = ROOT / "sites" / slug / "img"
    if img.is_dir():
        shutil.copytree(img, out / "img")
    return out


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        sys.exit(__doc__)
    try:
        # Placeholder links are allowed only in a preview: --preview, or a Cloudflare Pages
        # branch preview (CF_PAGES_BRANCH set and not main). Production (main) refuses them.
        branch = os.environ.get("CF_PAGES_BRANCH")
        preview = "--preview" in sys.argv or (branch is not None and branch != "main")
        print(build(args[0], preview=preview))
    except SiteError as e:
        sys.exit(f"build failed: {e}")
